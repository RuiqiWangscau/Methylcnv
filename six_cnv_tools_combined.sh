# Tool: CNVkit
# ============================================================
#!/bin/bash
#SBATCH --job-name=cnvkit_generated
#SBATCH --partition=kshcnormal
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=16
#SBATCH --time=1-00:00:00
#SBATCH --chdir=/public/home/wangruiqi/bam/cnv_benchmark/TOOLS
#SBATCH --output=/public/home/wangruiqi/bam/cnv_benchmark/TOOLS/cnvkit_generated_%j.out
#SBATCH --error=/public/home/wangruiqi/bam/cnv_benchmark/TOOLS/cnvkit_generated_%j.err

set -euo pipefail
export PATH=/public/home/wangruiqi/micromamba/envs/cnv-all/bin:$PATH
export OMP_NUM_THREADS="$SLURM_CPUS_PER_TASK"
export OPENBLAS_NUM_THREADS=1
export MPLBACKEND=Agg
BASE=/public/home/wangruiqi/bam/cnv_benchmark
BAM="$BASE/prepared_autosomes/sample.autosomes.sorted.bam"
FASTA="$BASE/prepared_autosomes/GRCh38.autosomes.fa"
OUT="$BASE/TOOLS/CNVkit_generated/${SLURM_JOB_ID}"
ID=sample.autosomes.sorted
test -s "$BAM"
test -s "$FASTA"
test -f "$BASE/normalize_cnv_calls.py"
mkdir -p "$OUT/resources" "$OUT/vcf"
cd "$OUT"
date
cnvkit.py version
set -x
# WGBS uses the WGS workflow: accessible genome, not CNV truth regions.
cnvkit.py access "$FASTA" -o resources/hg38.bed
# CNVkit generates hg38.target.bed and an empty hg38.antitarget.bed.
# WGS has no off-target bins. Batch also disables hybrid-specific edge correction.
cnvkit.py batch "$BAM" --method wgs --normal \
    --fasta "$FASTA" --targets "$OUT/resources/hg38.bed" \
    --target-avg-size 1000 --output-reference "$OUT/resources/hg38.FlatReference.cnn" \
    --output-dir "$OUT" --processes "$SLURM_CPUS_PER_TASK"
test -s "$OUT/hg38.target.bed"
test -f "$OUT/hg38.antitarget.bed"
cp "$OUT/hg38.target.bed" resources/hg38.target.bed
cp "$OUT/hg38.antitarget.bed" resources/hg38.antitarget.bed
cnvkit.py call "$ID.cns" -o "$ID.call.cns"
cnvkit.py export vcf "$ID.call.cns" > "vcf/$ID.cnvkit.vcf"
python "$BASE/normalize_cnv_calls.py" --format cnvkit \
    --input "$ID.call.cns" --output CNVkit.bed
set +x
cat > protocol.txt <<EOF
Analysis: CNVkit WGS mode applied to WGBS, autosomes only.
BAM: $BAM
Reference: $FASTA
Bins: generated by CNVkit from reference-accessible regions, target average size 1000 bp.
Antitargets: empty by design for WGS.
Reference: flat, no normal/control BAM supplied.
This is a newly generated configuration, not a reconstruction of the author's missing BED files.
No CNV truth labels or model predictions were used to construct bins.
EOF
echo SUCCESS > SUCCESS
echo "Results: $OUT"
date


